def lbgbf (mass, gbp):
    """
    A function to evaluate the luminosity at the end of the 
    FGB ( for those models that have one )
    Note that this function is only valid for LM & IM stars
    (JH 24/11/97)
    """
    lbgbf = (gbp[1]*mass**gbp[5] + gbp[2]*mass**gbp[8])/ \
            (gbp[3] + gbp[4]*mass**gbp[7] + mass**gbp[6])
    return lbgbf

def rgbf (mass, lum, gbp):
    """
    A function to evaluate radius on the GB.
    (JH 24/11/97)
    """
    a1 = min(gbp[20]/mass**gbp[21], gbp[22]/mass**gbp[23])
    rgbf = a1*(lum**gbp[18] + gbp[17]*lum**gbp[19])
    return rgbf


